"""
8-direction daemon facings. Every species now has a hand-drawn STANDING
facing set -- the same quadruped posture (feet on row 25) in every
direction, so turning never makes the animal appear to sit down:

- down       : the front map in animals.py (head + chest over front legs)
- down_right : a hand-drawn 3/4 view (DIAG_MAPS) -- turned head, angled
               body, tail off the far hip, two leg pairs
- right      : a hand-drawn profile (SIDE_MAPS)
- up         : DERIVED from the front map (face erased, inner ears
               filled) plus a hand-placed tail_overlay seen from behind
- up_right   : DERIVED from the diagonal map the same way (with the
               snout tucked behind the head via diag_erase)
- left side  : mirrors of the right-side family

The bird is the odd one out: it perches rather than stands, and its side
motion is the flight cycle in animal_motion.py, so it keeps its front map
for down and only carries a hand-drawn diagonal (beak poking past the
cheek, tail wedge off the hip).
"""

